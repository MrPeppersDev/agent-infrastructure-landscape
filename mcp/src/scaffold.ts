// Starter files for a stack (#397, roadmap 3.1): what `landscape init`
// writes and the blueprints share. Everything comes from the plan and the
// catalog data; a pick with no official container image or documented
// setting says so instead of guessing. Pure: callers pass the data.

import { toStackYaml, SITE, type StackPlan } from './composer.js';
import type { RecordLike } from './chooser.js';
import { procurementSheet, sheetToCsv } from './procurement.js';
import { contextPack } from './context-pack.js';

/** An official container setup (data/blueprints/images.json). */
export interface Image {
  id: string | null;
  name: string;
  image: string;
  port: number;
  env?: Record<string, string>;
  depends_on?: string[];
  source: string;
  note?: string;
}

/** docker-compose.yml for the picks that have an official single-image setup. */
export function composeFile(plan: StackPlan, images: Image[], header: string[]): string {
  const L: string[] = [...header.map((h) => `# ${h}`), 'services:'];
  const skipped: string[] = [];
  for (const l of plan.layers) {
    if (!l.pick) continue;
    const im = images.find((x) => x.id === l.pick!.item.id);
    if (!im || !im.image) {
      skipped.push(`#   ${l.label}: ${l.pick.item.name}${im?.note ? ' — ' + im.note : ' — library or hosted-only; no container'}`);
      continue;
    }
    if (im.depends_on?.length) {
      skipped.push(`#   ${l.label}: ${l.pick.item.name} — needs ${im.depends_on.join(', ')}; use the project's compose file: ${im.source}`);
      continue;
    }
    L.push(`  ${l.layer}:`, `    # ${l.pick.item.name} — ${im.source}`, `    image: ${im.image}`);
    if (im.port) L.push('    ports:', `      - "${im.port}:${im.port}"`);
    const env = Object.entries(im.env ?? {});
    if (env.length) {
      L.push('    environment:');
      for (const [k, v] of env) L.push(`      ${k}: "${String(v).replace(/"/g, '\\"')}"`);
    }
  }
  if (L[L.length - 1] === 'services:') L.push('  {}');
  if (skipped.length) L.push('', '# Not started here:', ...skipped);
  return L.join('\n') + '\n';
}

/** .env.example: the settings the official images document, and a pointer per hosted pick. */
function envExample(plan: StackPlan, images: Image[]): string {
  const L = [
    '# Settings for this stack. Values here come from each project\'s own setup docs;',
    '# hosted services list where to find their credentials instead of guessing variable names.',
    ''
  ];
  for (const l of plan.layers) {
    if (!l.pick) continue;
    const i = l.pick.item;
    const im = images.find((x) => x.id === i.id);
    L.push(`# ${l.label}: ${i.name} (${SITE}/systems/${i.id})`);
    const env = Object.entries(im?.env ?? {});
    if (env.length) for (const [k, v] of env) L.push(`${k}=${v}`);
    else if (im?.image) L.push('#   no settings required by the official image');
    else L.push(`#   credentials and settings: see ${i.url ?? 'the vendor docs'}`);
    L.push('');
  }
  return L.join('\n');
}

/** Every file `landscape init` writes, by relative path. */
export function initFiles(plan: StackPlan, ctx: { images: Image[]; packages: Record<string, string>; records: RecordLike[]; site?: string; today?: string }): Record<string, string> {
  const site = ctx.site ?? SITE;
  const today = ctx.today ?? new Date().toISOString().slice(0, 10);
  const pack = contextPack(plan, ctx.packages, site, today);
  const readme = [
    `# ${plan.product} stack`,
    '',
    `Generated ${today} by \`landscape init\` from the [AI Agent Infrastructure Landscape](${site}). Re-plan it at ${site}/build.`,
    '',
    '## Files',
    '',
    '- `stack.yml`: the stack, one catalogued system per layer. Check it any time with `npx landscape check stack.yml` or the "AI stack check" GitHub Action.',
    '- `docker-compose.yml`: a local starter for the picks with an official container image. It is not a production deployment.',
    '- `.env.example`: the settings those images document, and where each hosted service keeps its credentials.',
    '- `security-review.csv`: attestations, data handling, encryption, SSO/RBAC, deployment and licence per pick, each with its source.',
    '- `AGENTS-stack.md`: the section below, to paste into `AGENTS.md` or `CLAUDE.md` for coding agents.',
    '',
    '## Next steps',
    '',
    '1. `cp .env.example .env` and fill in the credentials.',
    '2. `docker compose up -d` for the self-hostable parts.',
    '3. Add the GitHub Action (`MrPeppersDev/agent-infrastructure-landscape@main` with `fail-on: archived`) so CI flags archived, acquired or drifting dependencies.',
    '',
    pack
  ].join('\n');
  return {
    'stack.yml': toStackYaml(plan.answers, plan.layers),
    'docker-compose.yml': composeFile(plan, ctx.images, [
      `Starter for this ${plan.product.toLowerCase()} stack, generated by \`landscape init\` from official images and ports in each project's docs.`,
      'A local starting point, not a production deployment: add auth, persistence and resource limits before real use.'
    ]),
    '.env.example': envExample(plan, ctx.images),
    'security-review.csv': sheetToCsv(procurementSheet(plan, ctx.records, site, today)),
    'AGENTS-stack.md': pack,
    'README.md': readme
  };
}
