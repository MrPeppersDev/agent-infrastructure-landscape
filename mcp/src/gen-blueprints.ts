// Generate blueprints/<product>/ from the stack composer plus the curated
// evidence in data/blueprints/: a reference stack per product type, cited
// "seen in production" write-ups, and a self-host starter compose file.
//
//   blueprints/<product>/README.md              picks, reasons, evidence, risk, cost
//   blueprints/<product>/stack.yml              the default (any hosting) stack
//   blueprints/<product>/stack.self-hosted.yml  everything self-hosted
//   blueprints/<product>/docker-compose.yml     starter for the self-hosted picks
//
// Run: cd mcp && npx tsc && node dist/gen-blueprints.js   (or `make blueprints`)
// Everything is regenerated from the catalog, so a lifecycle change or a
// new integration shows up the next time this runs.

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadChooserItems, loadRecords, loadEdges, loadMigrations, loadPricing, loadVectorPricing, loadStackPricing } from './data.js';
import { planStack, PRODUCTS, LAYER_BY_ID, SITE, type ProductType, type StackPlan, type LayerId } from './composer.js';
import { procurementSheet, sheetToMarkdown } from './procurement.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'blueprints');

interface Evidence {
  company: string;
  title: string;
  url: string;
  publisher: string;
  date: string;
  components: { layer: string; id: string | null; name: string }[];
  quote: string;
}
interface Image {
  id: string | null;
  name: string;
  image: string;
  port: number;
  env?: Record<string, string>;
  depends_on?: string[];
  source: string;
  note?: string;
}

const evidence = JSON.parse(readFileSync(join(ROOT, 'data', 'blueprints', 'evidence.json'), 'utf-8')) as Record<string, Evidence[]>;
const images = JSON.parse(readFileSync(join(ROOT, 'data', 'blueprints', 'images.json'), 'utf-8')) as Image[];

const ctx = {
  items: loadChooserItems(),
  records: loadRecords() as never,
  edges: loadEdges() as never,
  migrations: loadMigrations() as never,
  pricing: { stack: loadStackPricing() as never, memory: loadPricing() as never, vector: loadVectorPricing() as never }
};
const nameOf = new Map(ctx.items.map((i) => [i.id, i.name]));
const page = (id: string) => `${SITE}/systems/${id}`;
const link = (id: string) => `[${nameOf.get(id) ?? id}](${page(id)})`;
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const money = (n: number) => `$${n >= 100 ? Math.round(n).toLocaleString('en-US') : n.toFixed(2)}`;

function readme(product: ProductType, plan: StackPlan, self: StackPlan): string {
  const ev = evidence[product] ?? [];
  const L: string[] = [];
  L.push(`# Blueprint: ${PRODUCTS[product].label}`, '');
  L.push(
    `A reference stack for a ${PRODUCTS[product].label.toLowerCase()}, generated by the [stack composer](${SITE}/build?product=${product}) from the catalog and checked against the public write-ups below. ` +
      'Every pick links to its catalog page; every reason is a catalogued fact with its source. ' +
      `Regenerate with \`make blueprints\`; open it in the builder to change requirements: [${SITE}/build?product=${product}](${SITE}/build?product=${product}).`,
    ''
  );
  L.push('## The stack', '', '| Layer | Pick | Why (cited) | Runners-up |', '|---|---|---|---|');
  for (const l of plan.layers) {
    const why = (l.pick?.reasons ?? []).slice(0, 2).map((r) => (r.citation ? `[${cell(r.text.slice(0, 90))}](${r.citation})` : cell(r.text.slice(0, 90)))).join('<br>');
    const alt = l.whyNot.slice(0, 2).map((w) => link(w.id)).join(', ');
    L.push(`| ${l.label} | ${l.pick ? link(l.pick.item.id) : '—'} | ${why} | ${alt} |`);
  }
  L.push('');

  L.push('## Seen in production', '');
  if (!ev.length) L.push('_No public write-up found yet. Share yours with the "We use this stack" issue template._', '');
  const picks = new Map(plan.layers.filter((l) => l.pick).map((l) => [l.layer as string, l.pick!.item.id]));
  const differs: string[] = [];
  for (const e of ev) {
    L.push(`- **${e.company}**: [${e.title}](${e.url}) (${e.publisher}${e.date ? ', ' + e.date : ''})`);
    const comps = e.components.map((c) => {
      const same = c.id && picks.get(c.layer) === c.id;
      if (c.id && picks.has(c.layer) && !same) differs.push(`${e.company} uses ${link(c.id)} for ${LAYER_BY_ID[c.layer as LayerId]?.label.toLowerCase() ?? c.layer} (blueprint: ${link(picks.get(c.layer)!)})`);
      return `${c.id ? link(c.id) : c.name}${same ? ' ✓' : ''}`;
    });
    L.push(`  - Components: ${comps.join(', ')}`);
    if (e.quote) L.push(`  - "${e.quote}"`);
  }
  if (ev.length) L.push('', '✓ = the same system as the blueprint pick for that layer.', '');
  if (differs.length) {
    L.push('**Where production write-ups chose differently** (each is a live alternative worth evaluating):', '');
    for (const d of [...new Set(differs)]) L.push(`- ${d}`);
    L.push('');
  }

  L.push(`## Risk: ${plan.risk.level} (${plan.risk.score})`, '');
  if (plan.risk.factors.length) for (const f of plan.risk.factors) L.push(`- +${f.points} ${f.detail}`);
  else L.push('No risk factors recorded.');
  const gaps = plan.security.items.filter((s) => s.status !== 'addressed');
  L.push('', `## Security (OWASP Top 10 for LLM applications)`, '');
  L.push(`${plan.security.items.length - gaps.length} of 10 risks have a component aimed at them ([OWASP list](${plan.security.source})).`);
  for (const s of gaps) L.push(`- **${s.id} ${s.risk}** (${s.status}): ${s.note}`);
  L.push('');

  if (plan.cost) {
    const c = plan.cost;
    const w = c.workload;
    const r = c.range && c.range.estimatedLines ? c.range : null;
    if (r) {
      L.push(`## Monthly cost at ${w.runsPerDay.toLocaleString('en-US')} runs/day: ${money(r.lowUsd)} to ${money(r.highUsd)}${r.unquotedLines ? ` plus ${r.unquotedLines} "contact sales" line${r.unquotedLines === 1 ? '' : 's'}` : ''}`, '');
      L.push(`${money(c.knownMonthlyUsd)} from published list prices (checked ${c.checked}); the rest are self-hosting estimates for components with no published price (checked ${r.checked}). ${w.llmCallsPerRun} model calls of ${w.inputTokensPerCall} in / ${w.outputTokensPerCall} out tokens per run. Change the workload on [/build](${SITE}/build?product=${product}).`, '');
    } else {
      L.push(`## Monthly cost at ${w.runsPerDay.toLocaleString('en-US')} runs/day: ${c.lowerBound ? 'at least ' : ''}${money(c.knownMonthlyUsd)}`, '');
      L.push(`From published list prices (checked ${c.checked}); ${w.llmCallsPerRun} model calls of ${w.inputTokensPerCall} in / ${w.outputTokensPerCall} out tokens per run. Change the workload on [/build](${SITE}/build?product=${product}).`, '');
    }
    L.push('| Layer | System | Monthly | Plan / assumption |', '|---|---|---|---|');
    for (const x of c.lines) {
      const amt = x.status === 'priced' ? money(x.monthlyUsd ?? 0) : x.status === 'contact-sales' ? 'contact sales' : x.estimate ? `${money(x.estimate.lowUsd)} to ${money(x.estimate.highUsd)} (estimate)` : '—';
      const how = x.status === 'priced' || x.status === 'contact-sales' ? x.plan || (x.caveat ?? '') : x.estimate ? `Self-hosting estimate: ${x.estimate.basis}. ${x.estimate.sources.map((u, i) => `[source ${i + 1}](${u})`).join(' ')}` : (x.caveat ?? '');
      L.push(`| ${LAYER_BY_ID[x.layer as LayerId]?.label ?? x.layer} | ${link(x.id)} | ${amt} | ${cell(how)} |`);
    }
    L.push('');
    if (r) L.push(`_${r.note}_`, '');
    const sw = plan.layers.filter((l) => l.exit?.switching?.to);
    if (sw.length) {
      L.push('**Cost to switch** (to the exit-path fallback, at this workload):', '');
      for (const l of sw) {
        const x = l.exit!.switching!;
        L.push(`- ${l.label}: ${link(l.pick!.item.id)} → ${link(x.to!.id)}: ${x.deltaNote}${x.sharedIntegrations ? `; documented to work with ${x.sharedWith.slice(0, 3).join(', ')} in this stack` : '; no documented integration with the other picks'}${x.hasMigrationNotes ? '; migration notes in the catalog' : ''}.`);
      }
      L.push('');
    }
  }

  // Security review sheet (#366): the buyer cells of every pick with sources.
  const sheet = procurementSheet(plan, loadRecords() as never, SITE);
  L.push('## Security review sheet', '', '<details><summary>Attestations, data handling, encryption, SSO/RBAC, deployment, licence, SDKs, protocols, maturity, HQ and pricing for every pick, with sources</summary>', '');
  L.push(sheetToMarkdown(sheet).split('\n').slice(4).join('\n'));
  L.push('</details>', '', `Download the same sheet as CSV from [/build](${SITE}/build?product=${product}) or with \`landscape stack ${product} --sheet sheet.csv\`.`, '');
  L.push('## Self-hosted variant', '');
  L.push('`stack.self-hosted.yml` picks only self-hostable components and adds model serving. `docker-compose.yml` starts the ones with an official single-image setup; it is a local starter, not a production deployment.', '');
  L.push('| Layer | Pick |', '|---|---|');
  for (const l of self.layers) L.push(`| ${l.label} | ${l.pick ? link(l.pick.item.id) : '—'} |`);
  L.push('');
  L.push('## Files', '', '- `stack.yml`: check it with `npx landscape check stack.yml` or the "AI stack check" GitHub Action.', '- `stack.self-hosted.yml`: the self-hosted variant.', '- `docker-compose.yml`: a starter for the self-hosted variant.', '');
  return L.join('\n');
}

function compose(product: ProductType, self: StackPlan): string {
  const L: string[] = [
    `# Starter for the self-hosted ${PRODUCTS[product].label.toLowerCase()} blueprint (blueprints/${product}/stack.self-hosted.yml).`,
    '# Generated by `make blueprints` from data/blueprints/images.json: official images and ports from each project\'s docs.',
    '# A local starting point, not a production deployment: add auth, persistence and resource limits before real use.',
    'services:'
  ];
  const skipped: string[] = [];
  for (const l of self.layers) {
    if (!l.pick) continue;
    const im = images.find((x) => x.id === l.pick!.item.id);
    if (!im || !im.image) {
      skipped.push(`#   ${l.label}: ${l.pick.item.name}${im?.note ? ' — ' + im.note : ' — library or hosted-only; no container'}`);
      continue;
    }
    if (im.depends_on?.length) {
      skipped.push(`#   ${l.label}: ${l.pick.item.name} — needs ${im.depends_on.join(', ')}; use the project's compose file: ${im.source}`);
      continue;
    }
    const svc = l.layer;
    L.push(`  ${svc}:`, `    # ${l.pick.item.name} — ${im.source}`, `    image: ${im.image}`);
    if (im.port) L.push('    ports:', `      - "${im.port}:${im.port}"`);
    const env = Object.entries(im.env ?? {});
    if (env.length) {
      L.push('    environment:');
      for (const [k, v] of env) L.push(`      ${k}: "${String(v).replace(/"/g, '\\"')}"`);
    }
  }
  if (L[L.length - 1] === 'services:') L.push('  {}');
  if (skipped.length) L.push('', '# Not started here:', ...skipped);
  return L.join('\n') + '\n';
}

mkdirSync(OUT, { recursive: true });
const index: string[] = [
  '# Reference blueprints',
  '',
  'One reference stack per product type, generated by the [stack composer](' + SITE + '/build) from the catalog and checked against public write-ups of production systems. Each folder has a README (picks, cited reasons, production evidence, risk, OWASP coverage, cost), a `stack.yml`, a self-hosted variant and a `docker-compose.yml` starter.',
  '',
  'Regenerate with `make blueprints` after catalog changes. Evidence lives in `data/blueprints/evidence.json`, images in `data/blueprints/images.json`.',
  '',
  '| Blueprint | Risk | Production write-ups |',
  '|---|---|---|'
];
for (const product of Object.keys(PRODUCTS) as ProductType[]) {
  const plan = planStack(ctx, { product } as never);
  const self = planStack(ctx, { product, hosting: 'self', oss: true } as never);
  const dir = join(OUT, product);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'README.md'), readme(product, plan, self));
  writeFileSync(join(dir, 'stack.yml'), plan.stackYaml);
  writeFileSync(join(dir, 'stack.self-hosted.yml'), self.stackYaml);
  writeFileSync(join(dir, 'docker-compose.yml'), compose(product, self));
  index.push(`| [${PRODUCTS[product].label}](${product}/README.md) | ${plan.risk.level} | ${(evidence[product] ?? []).length} |`);
}
writeFileSync(join(OUT, 'README.md'), index.join('\n') + '\n');
if (!existsSync(join(OUT, 'README.md'))) process.exit(1);
console.log(`wrote ${Object.keys(PRODUCTS).length} blueprints to ${OUT}`);
