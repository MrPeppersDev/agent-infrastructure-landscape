"""Build results/leaderboard.{md,json} from every run's summary.json.

For each (dataset, answer model, judge model) the latest real (non-fake)
run of each system wins. Fake/offline runs are ignored.

    python -m memory_bench.report
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "results" / "runs"


def main() -> int:
    best: dict[tuple, dict] = {}
    for p in sorted(RUNS.glob("*/summary.json")):
        s = json.loads(p.read_text())
        if s.get("fake"):
            continue
        for sysname, m in s["systems"].items():
            if not m.get("answered"):
                continue
            key = (s["dataset"], s["answer_model"], s["judge_model"], sysname)
            if key not in best or s["finished_at"] > best[key]["finished_at"]:
                best[key] = {**m, "system": sysname, "run_id": s["run_id"], "finished_at": s["finished_at"],
                             "version": s["versions"].get(sysname, ""), "dataset": s["dataset"],
                             "answer_model": s["answer_model"], "judge_model": s["judge_model"],
                             "k": s["k"], "extraction_model": s["extraction_model"]}
    rows = sorted(best.values(), key=lambda r: (r["dataset"], r["answer_model"], -(r["accuracy_macro"] or 0)))
    (ROOT / "results" / "leaderboard.json").write_text(json.dumps(rows, indent=1) + "\n")

    lines = ["# Memory benchmark leaderboard", "",
             "Generated by `python -m memory_bench.report` from `results/runs/*/summary.json`. "
             "Same answer model, judge, k and data for every system in a table; only the memory layer differs. "
             "See [README](../README.md) for methodology.", ""]
    groups: dict[tuple, list] = {}
    for r in rows:
        groups.setdefault((r["dataset"], r["answer_model"], r["judge_model"]), []).append(r)
    if not groups:
        lines.append("_No real runs yet. Run the `Memory benchmark` workflow or `python -m memory_bench.run`._")
    for (dsname, am, jm), rs in groups.items():
        types = sorted({t for r in rs for t in r["by_type"]})
        lines += [f"## {dsname} — answer `{am}`, judge `{jm}`", "",
                  "| System | Macro acc. | Overall | " + " | ".join(types) + " | Abstention | p50 retrieve | Version | Run |",
                  "|---|---:|---:|" + "---:|" * len(types) + "---:|---:|---|---|"]
        for r in rs:
            cells = [f"{r['by_type'].get(t, {}).get('accuracy', '–')}" for t in types]
            lines.append(f"| {r['system']} | **{r['accuracy_macro']}** | {r['accuracy']} | " + " | ".join(cells)
                         + f" | {r['abstention_accuracy'] if r['abstention_accuracy'] is not None else '–'} | "
                         f"{r['retrieve_ms_p50']} ms | {r['version']} | `{r['run_id']}` |")
        lines.append("")
    (ROOT / "results" / "leaderboard.md").write_text("\n".join(lines) + "\n")
    print(f"leaderboard: {len(rows)} rows in {len(groups)} table(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
